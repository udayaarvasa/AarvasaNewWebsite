"""Rebuild all five REEF models for local PlayCanvas review; uploads nothing."""
import hashlib
import json
import pathlib
import shutil
import struct
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
MODELS = [
    (996, "reef-996-dubai-production-city", "reef-996-massing-v2.py", 26, 16, 2.15),
    (997, "reef-997-dubai-islands", "reef-997-massing.py", -50, 16, 2.2),
    (998, "reef-998-dlrc", "reef-998-massing-v3.py", 26, 16, 2.2),
    (999, "reef-999-al-furjan", "reef-999-massing.py", 28, 16, 2.2),
    (1000, "reef-1000-dlrc", "reef-1000-massing.py", 32, 19, 2.2),
]

if __name__ == "__main__":
    staging = ROOT / "research/reef-preview-2026-11-08/models"
    staging.mkdir(parents=True, exist_ok=True)
    manifest = {}
    for number, slug, script, yaw, pitch, distance in MODELS:
        target = staging / f"reef-{number}.glb"
        subprocess.run([sys.executable, str(ROOT / "tools" / script), str(target)], check=True)
        data = target.read_bytes()
        gltf = json.loads(data[20:20 + struct.unpack_from("<I", data, 12)[0]])
        positions = [gltf["accessors"][p["attributes"]["POSITION"]] for m in gltf["meshes"] for p in m["primitives"]]
        # Vertices are centred, at 1:10. Google's map uses metre-scale models
        # scaled by 10, so lift the centroid by half the measured real height.
        height_metres = (max(a["max"][1] for a in positions) - min(a["min"][1] for a in positions)) * 10
        digest = hashlib.sha256(data).hexdigest()
        ident = hashlib.sha256(f"aarvasa-reference-review:{slug}".encode()).hexdigest()[:24]
        key = f"m/{ident}/{digest[:16]}"
        directory = ROOT / "public/media" / key
        directory.mkdir(parents=True, exist_ok=True)
        shutil.copy2(target, directory / "scene.glb")
        view = {"yawDeg": yaw, "pitchDeg": pitch, "distanceFactor": distance}
        manifest[slug] = {
            "mediaId": ident, "kind": "MODEL", "format": "GLB", "storageKey": key,
            "entryFile": "scene.glb", "contentHash": digest, "sizeBytes": len(data),
            "poster": None, "processingVersion": "local-reference-review-2026-11-08",
            "altText": f"REEF {number}, an Aarvasa exterior reconstruction from developer references. Local review; dimensions are approximate, not an official developer model.",
            # The existing viewer requires this value to resolve same-origin files.
            # This registry is attached ONLY by the development-only preview gate.
            "review": "approved", "hosting": "site", "provenance": "AARVASA_RECONSTRUCTION",
            "view": view, "mobileView": {**view, "distanceFactor": 2.4},
            "mapOverlay": {"baseOffsetMetres": round(height_metres / 2, 5)},
            "lighting": {"keyPitchDeg": 35, "keyYawDeg": 65, "intensity": 1.35, "ambient": 0.4, "shadows": True},
        }
    (staging / "manifest.json").write_text(json.dumps(manifest, indent=2))
    (ROOT / "src/lib/reef-preview-models.ts").write_text(
        '// Generated by tools/reef-preview-models.py. Local review only; not public approvals.\n'
        'import type { ProjectImmersiveMedia } from "./project-types";\n'
        'export const REEF_REVIEW_MODELS: Readonly<Record<string, ProjectImmersiveMedia>> = '
        + json.dumps(manifest, indent=2) + ';\n')
    print("Prepared five same-origin GLBs. Production approvals are unchanged.")

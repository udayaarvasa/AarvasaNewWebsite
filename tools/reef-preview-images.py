"""Refresh local REEF review imagery from the developer's project pages.

Run after saving the five pages and image lists under research/reef-preview-2026-11-08.
Writes web-sized, labelled developer renders and a source/checksum manifest.
"""
import concurrent.futures
import hashlib
import io
import json
import pathlib
import re
import urllib.parse
import urllib.request
import sys
from PIL import Image, ImageOps

ROOT = pathlib.Path(__file__).resolve().parents[1]
SOURCE = ROOT / "research/reef-preview-2026-11-08"
SLUGS = {996: "reef-996-dubai-production-city", 997: "reef-997-dubai-islands", 998: "reef-998-dlrc", 999: "reef-999-al-furjan", 1000: "reef-1000-dlrc"}
CACHE = json.loads((SOURCE / "download-manifest.json").read_text()) if (SOURCE / "download-manifest.json").exists() else {}

def collect(n):
    rows = json.loads((SOURCE / f"{n}-images.json").read_text())
    chosen, seen = [], set()
    # Six amenities plus one example of each residence type. Names and URLs
    # belong to the project's own page; filenames alone are not attribution.
    for row in rows:
        src, alt = row["src"], row["alt"]
        if not alt or not src.startswith("/_next/image?url="):
            continue
        url = urllib.parse.parse_qs(urllib.parse.urlsplit(src).query)["url"][0]
        if urllib.parse.urlsplit(url).hostname != "cdn.reefdevelopments.ae":
            continue
        residence = alt.startswith(("RESIDENCE", "DUPLEX", "PENTHOUSE", "SKY VILLA"))
        if url in seen or (residence and alt in seen):
            continue
        if not residence and sum(not r["residence"] for r in chosen) >= 6:
            continue
        seen.update((url, alt))
        chosen.append({"source": url, "label": alt, "residence": residence})
    # Include the developer's project-wide exterior as the review cover.
    for row in rows:
        if "latest-projects" in row["src"]:
            path = urllib.parse.parse_qs(urllib.parse.urlsplit(row["src"]).query)["url"][0]
            chosen.append({"source": urllib.parse.urljoin("https://reefdevelopments.ae", path), "label": "Exterior architecture", "residence": False})
            break
    return [(n, i, row) for i, row in enumerate(chosen)]

def download(task):
    n, i, row = task
    ident = f"reef-{n}-official-{i+1:02d}"
    directory = ROOT / f"public/images/reef-{n}/official-review"
    directory.mkdir(parents=True, exist_ok=True)
    output = directory / f"{ident}-3x2.jpg"
    previous = next((r for r in CACHE.get(SLUGS[n], []) if r["id"] == ident and r["source"] == row["source"]), None)
    if previous and output.exists() and "--refresh" not in sys.argv:
        return n, previous
    data = urllib.request.urlopen(row["source"], timeout=45).read()
    image = Image.open(io.BytesIO(data)).convert("RGB")
    # Preserve the complete source frame. Gallery uses contain; no architectural
    # elements are invented or removed to fit an aspect ratio.
    image.thumbnail((1600, 1600), Image.Resampling.LANCZOS)
    image.save(output, quality=88, optimize=True)
    return n, {"id": ident, "dir": f"/images/reef-{n}/official-review", "ratios": ["3x2"],
        "alt": f"REEF {n}: {row['label'].title()} — developer render",
        "caption": f"{row['label'].title()} · REEF {n} · Developer render",
        "origin": "render", "source": row["source"], "sourcePage": f"https://reefdevelopments.ae/projects/reef-{n}",
        "retrieved": "2026-11-08", "sourceSha256": hashlib.sha256(data).hexdigest(),
        "width": image.width, "height": image.height}

if __name__ == "__main__":
    tasks = [task for n in SLUGS for task in collect(n)]
    result = {slug: [] for slug in SLUGS.values()}
    with concurrent.futures.ThreadPoolExecutor(max_workers=8) as pool:
        for n, row in pool.map(download, tasks):
            result[SLUGS[n]].append(row)
    (SOURCE / "download-manifest.json").write_text(json.dumps(result, indent=2))
    (ROOT / "src/lib/reef-preview-images.ts").write_text(
        '// Generated by tools/reef-preview-images.py. Local review, 8 November 2026.\n'
        'import type { ProjectCuratedImage } from "./project-types";\n'
        'export const REEF_REVIEW_IMAGES: Readonly<Record<string, readonly ProjectCuratedImage[]>> = '
        + json.dumps({s: [{k: v for k, v in row.items() if k in ("id", "dir", "ratios", "alt", "caption", "origin")} for row in rows] for s, rows in result.items()}, indent=2) + ';\n')
    print(f"Downloaded {len(tasks)} developer renders across five projects.")
